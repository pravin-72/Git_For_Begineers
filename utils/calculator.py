def add_nums(num1, num2):
    return num1+num2

def divide_nums(a, b):
    if b == 0:
        raise ValueError("Cannot divide by zero.")
    return a / b
def subract_nums(num1, num2):
    return num1-num2

def power_nums(base, exponent):
    return base ** exponent
def multiply_nums(num1, num2):
    return num1 * num2
